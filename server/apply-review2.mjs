let done = 0;
for (const [file, plan] of Object.entries(plans)) {
  const p = DIR + file;
  const lines = fs.readFileSync(p, "utf8").split("\n");
  const startIdx = lines.findIndex(l => new RegExp(plan.start).test(l) && l.includes("问句表"));
  if (startIdx < 0) { console.error(`${file}: 找不到问句表`); continue; }
  let endIdx = lines.length;
  for (let i = startIdx + 1; i < lines.length; i++) if (/^#{1,3} /.test(lines[i])) { endIdx = i; break; }
  const idxs = [];
  for (let i = startIdx; i < endIdx; i++) if (rowRe.test(lines[i])) idxs.push(i);
  if (!idxs.length) { console.error(`${file}: 无题行`); continue; }
  const oldRows = new Map(idxs.map(i => [Number(lines[i].match(rowRe)[2]), lines[i]]));
  const qPrefix = lines[idxs[0]].match(rowRe)[1];
  const used = new Set();
  const newRows = plan.seq.map((item, k) => {
    const no = k + 1;
    if (item.startsWith("NEW|||")) return `| ${qPrefix}${no} | ` + item.slice(6).split("|").join(" | ") + " |";
    const o = Number(item);
    used.add(o);
    const src = oldRows.get(o);
    if (!src) throw new Error(`${file}: 旧题 ${o} 不存在`);
    return src.replace(rowRe, `| ${qPrefix}${no} |`);
  });
  const missing = [...oldRows.keys()].filter(x => !used.has(x));
  if (missing.length) throw new Error(`${file}: 未被引用的旧题 ${missing.join(",")}`);
  if (newRows.length > idxs.length) {
    const at = idxs[idxs.length - 1];
    const blanks = [];
    for (let k = 0; k < newRows.length - idxs.length; k++) blanks.push("");
    lines.splice(at + 1, 0, ...blanks);
    const base = idxs.length;
    for (let k = base; k < newRows.length; k++) idxs.push(at + 1 + (k - base));
  }
  idxs.forEach((lineIdx, k) => { lines[lineIdx] = newRows[k]; });
  // 修补
  let fixedN = 0;
  for (const [from, to] of (plan.fixes || [])) {
    const li = lines.findIndex(l => l.includes(from));
    if (li >= 0) { lines[li] = lines[li].replace(from, to); fixedN++; }
  }
  fs.writeFileSync(p, lines.join("\n"));
  done++;
  console.log(`${file}: ${oldRows.size}→${newRows.length} 题${fixedN ? "，修补 " + fixedN : ""}`);
}
console.log(`完成 ${done}/${Object.keys(plans).length} 册`);
